# Detector: yolov9_s_608 | yolov9_t_384. OCR: cct_s_v1_global | european_vit_v2.
BABA_PLATE_DETECTOR=${BABA_PLATE_DETECTOR:-}
BABA_PLATE_OCR=${BABA_PLATE_OCR:-}

# =========================================================================
# Event manager
# =========================================================================
BABA_EVENT_TRACK_TIMEOUT_MS=5000
BABA_EVENT_MIN_TRACK_LIFETIME_MS=1500
BABA_EVENT_MIN_OBSERVATIONS=5
BABA_THUMBNAIL_MAX_WIDTH=640
BABA_EVENT_DWELL_MS=30000

# =========================================================================
# Recorder
# =========================================================================
BABA_RECORDER_SEGMENT_SECONDS=300

# =========================================================================
# Postgres
# =========================================================================
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
# Empty = asyncpg default (right for the bundled non-TLS Postgres).
# Set to 'require' or 'verify-full' for external managed Postgres.
POSTGRES_SSLMODE=${POSTGRES_SSLMODE}

# =========================================================================
# NATS authentication
# =========================================================================
# Required: the bus never runs open. The server is given only bcrypt hashes
