# shellcheck shell=bash
# .env file generator:
#
#   envgen_write          → create fresh .env from current values (first install)
#   envgen_merge_missing  → re-read existing .env, append only keys it's missing
#   envgen_apply          → set the named keys to the wizard's values (reconfigure)
#   envgen_retire         → drop keys this version no longer reads (upgrade, deploy)
#
# Critical invariant: secrets are NEVER overwritten. The wizard reads
# BABA_SECRET_KEY and the passwords back from .env before anything is
# written, so a reconfigure hands envgen_apply the values already there
# (a new key would invalidate every signed JWT in flight).

# Copy .env to .env.bak.<stamp> before a change. One run may change the file
# in several steps within a second (retire, merge, apply): the first backup of
# that second is the pre-run state, so a later step never overwrites it.
envgen_backup() {
    local target="$1" bak
    bak="${target}.bak.$(date +%Y%m%d-%H%M%S)"
    [[ -e "$bak" ]] && return 0
    cp "$target" "$bak"
    chmod 600 "$bak"
    c_dim "  Backed up existing .env → $bak"
}

# All keys we know about. Order is preserved on write so the produced
# .env stays diff-friendly across versions. Comments + section headers
# live in the template below; values come from the matching shell vars.
envgen_write() {
    local target="$1"
    # Backup any existing file so the operator can roll back if the
    # wizard wrote something they don't like.
    [[ -f "$target" ]] && envgen_backup "$target"

    # The template uses parameter expansion so empty vars come out as
    # empty values, never as the literal `${VAR}` text. Created 600 before
    # any secret is written: the file carries BABA_SECRET_KEY and every
    # service password, so it must never land world-readable under the
    # operator's umask.
    (umask 077; : > "$target")
    cat > "$target" <<EOF
# BABA configuration — generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Re-running install.sh appends keys missing from this file; only
# --reconfigure changes existing values, and only the ones its wizard asks about.

# =========================================================================
# Storage paths (host)
# =========================================================================
BABA_MODELS_HOST=${BABA_MODELS_HOST}
BABA_STATE_HOST=${BABA_STATE_HOST}
BABA_MEDIA_HOST=${BABA_MEDIA_HOST}

# Runtime uid:gid for the non-root service containers. The bundled images bake
# user 1000; the host storage tiers (models, media, state/api) are chowned to
# this by install.sh so the containers can write. Change only if you rebuilt
# the images with a different uid.
BABA_UID=${BABA_UID}
BABA_GID=${BABA_GID}

# =========================================================================
# Resource governance (shared-host only — leave empty on a dedicated host)
# =========================================================================
# When BABA shares a host with other stacks, cap/prioritise the baba.slice
# cgroup (every container runs under it). Empty = unconstrained. Applied by
# install.sh via 'systemctl set-property' (live + persists reboots).
#   BABA_MEM_LIMIT: hard memory ceiling for ALL baba containers, e.g. 8G.
#     Exceeding it OOM-kills the largest baba process (protects co-tenants).
#   BABA_CPU_WEIGHT: scheduler weight (default 100). 1000 = 10x priority under
#     contention; soft (no idle waste), protects BABA's real-time pipeline.
BABA_MEM_LIMIT=${BABA_MEM_LIMIT:-}
BABA_CPU_WEIGHT=${BABA_CPU_WEIGHT:-}

# =========================================================================
# Hardware variant
# =========================================================================
# cpu | nvidia | intel. Detected by install.sh; override here for testing.
BABA_VARIANT=${BABA_VARIANT}

# Which compose files 'docker compose' merges: the hardware-neutral base plus
# the GPU override for this variant (nvidia/intel). Set by install.sh from the
# variant so plain 'docker compose' commands on the host pick up the right
# deploy layer. Keep in sync with BABA_VARIANT if you change it by hand.
COMPOSE_FILE=${COMPOSE_FILE}

# The image tag for this checkout, written by install.sh: on a release tag it is
# that release's version and pins its <variant>-<version> images; empty takes
# the moving <variant> tag. It follows the checkout, so it is not edited by hand.
BABA_IMAGE_TAG=${BABA_IMAGE_TAG}

# The ingestor's one video decoder. Empty = the variant's (ffmpeg-nvdec-nv12
# on nvidia, vaapi-nv12 on intel, software on cpu). Named only for a host the
# default does not suit: an Intel iGPU gets qsv-nv12 (install.sh sets it).
BABA_DECODER_BACKEND=${BABA_DECODER_BACKEND:-}

# Host 'render' group gid, added to the intel GPU services (group_add) so the
# uid-1000 containers can open /dev/dri/renderD128. Detected by install.sh on
# the intel variant (Debian 993, Ubuntu 110). Only used by docker-compose.intel.yml.
BABA_INTEL_RENDER_GID=${BABA_INTEL_RENDER_GID:-110}

# =========================================================================
# Detector
# =========================================================================
# The backend follows the variant: tensorrt / openvino / onnxruntime.
# Set by install.sh: nv12-baked graph on nvidia (the GPU decoders write NV12),
# nv12-baked or plain on intel (OpenVINO wraps a plain one), plain on cpu.
BABA_DETECTOR_MODEL=${BABA_DETECTOR_MODEL}
# Detector head family: "dfine" (D-FINE / RT-DETR, plain [0,1] input) or
# "rfdetr" (RF-DETR / LWDETR, 91-class dets+labels output, ImageNet norm +
# square stretch). Set by install.sh from the GPU tier (detect_gpu_tier):
# a discrete GPU (Arc) gets rfdetr, a budget iGPU gets the lighter dfine CNN.
BABA_DETECTOR_MODEL_FAMILY=${BABA_DETECTOR_MODEL_FAMILY:-dfine}
# OpenVINO inference precision override (f16 | f32). Empty = backend self-selects
# (it verifies fp16 stability per model). install.sh sets f16 for RF-DETR on Arc.
BABA_DETECTOR_OV_PRECISION=${BABA_DETECTOR_OV_PRECISION:-}
BABA_DETECTOR_BATCH=8
BABA_DETECTOR_BATCH_WAIT_MS=20
BABA_DETECTOR_CONF=0.10
BABA_DETECTOR_IOU=0.45
BABA_DETECTOR_INPUT_SIZE=640
BABA_DEVICE_ID=0

# =========================================================================
# Tracker (Norfair IoU+Kalman + inline appearance re-ID)
# =========================================================================
BABA_TRACKER_CLASSES=0,1,2,3,5,7,14,15,16
BABA_TRACKER_FPS=15

# =========================================================================
# Embedder (DINOv2 body re-ID + AuraFace face re-ID)
# =========================================================================
BABA_EMBEDDER_MODEL=/models/osnet_x0_25_msmt17.onnx
BABA_FACE_DETECTOR_MODEL=/models/face_yunet.onnx
BABA_FACE_EMBEDDER_MODEL=/models/face_auraface.onnx

