BABA_GO2RTC_API_USER=${BABA_GO2RTC_API_USER}
BABA_GO2RTC_API_PASSWORD=${BABA_GO2RTC_API_PASSWORD}

# =========================================================================
# API
# =========================================================================
BABA_API_PORT=${BABA_API_PORT}
BABA_ADMIN_USERNAME=${BABA_ADMIN_USERNAME}
# Empty = api generates a random password on first boot and persists it
# to \${BABA_STATE_HOST}/api/bootstrap_admin_password. Set here only if
# you want to override (e.g. CI tests).
BABA_ADMIN_PASSWORD=${BABA_ADMIN_PASSWORD}
# Required: signs JWT cookies. install.sh generated this once;
# never change without accepting that every active session breaks.
BABA_SECRET_KEY=${BABA_SECRET_KEY}
# true behind HTTPS, false for plain-HTTP localhost dev.
BABA_COOKIE_SECURE=${BABA_COOKIE_SECURE}
# Origins allowed to call the API. Empty = dev defaults (localhost:5173).
# Set to your public hostname(s) when behind a reverse proxy.
BABA_CORS_ORIGINS=${BABA_CORS_ORIGINS}

# AI auto-describe loop — off by default (per-call cost to Anthropic / OpenAI).
BABA_AI_AUTO_DESCRIBE=0
BABA_AI_AUTO_DESCRIBE_INTERVAL_S=120
BABA_AI_AUTO_DESCRIBE_BATCH=5
EOF
    chmod 600 "$target"
    c_ok "Wrote $target"
}

# Add any keys from the current shell's set that the existing .env is
# missing. Used on re-run / upgrade so a newly-added variable lands in
# the file without disturbing what the operator already set. Returns
# the number of keys appended.
envgen_merge_missing() {
    local target="$1"
    if [[ ! -f "$target" ]]; then
        c_err "envgen_merge_missing: $target does not exist"
        return 1
    fi
    # Known keys this version of install.sh wants present. Keep in
    # sync with envgen_write's template. Skip values: we don't seed
    # passwords / secrets on merge — those have their own gen path.
    local keys=(
        BABA_MODELS_HOST BABA_STATE_HOST BABA_MEDIA_HOST
        BABA_UID BABA_GID
        BABA_MEM_LIMIT BABA_CPU_WEIGHT
        BABA_VARIANT COMPOSE_FILE BABA_IMAGE_TAG BABA_DECODER_BACKEND BABA_INTEL_RENDER_GID
        BABA_DETECTOR_MODEL
        BABA_DETECTOR_MODEL_FAMILY BABA_DETECTOR_OV_PRECISION BABA_DETECTOR_BATCH
        BABA_DETECTOR_BATCH_WAIT_MS BABA_DETECTOR_CONF BABA_DETECTOR_IOU
        BABA_DETECTOR_INPUT_SIZE BABA_DEVICE_ID
        BABA_TRACKER_CLASSES BABA_TRACKER_FPS
        BABA_EMBEDDER_MODEL BABA_FACE_DETECTOR_MODEL BABA_FACE_EMBEDDER_MODEL
        BABA_PLATE_DETECTOR BABA_PLATE_OCR
        BABA_EVENT_TRACK_TIMEOUT_MS BABA_EVENT_MIN_TRACK_LIFETIME_MS
        BABA_EVENT_MIN_OBSERVATIONS BABA_THUMBNAIL_MAX_WIDTH BABA_EVENT_DWELL_MS
        BABA_RECORDER_SEGMENT_SECONDS
        POSTGRES_USER POSTGRES_PASSWORD POSTGRES_DB POSTGRES_SSLMODE
        NATS_USER NATS_PASSWORD BABA_PEER_NATS_PASSWORD
        BABA_GO2RTC_API_USER BABA_GO2RTC_API_PASSWORD
        BABA_API_PORT BABA_ADMIN_USERNAME BABA_ADMIN_PASSWORD BABA_SECRET_KEY
        BABA_COOKIE_SECURE BABA_CORS_ORIGINS
        BABA_AI_AUTO_DESCRIBE BABA_AI_AUTO_DESCRIBE_INTERVAL_S BABA_AI_AUTO_DESCRIBE_BATCH
    )
    # Heal perms on a legacy .env that predates the 600 default.
    chmod 600 "$target"
    local appended=0
    local k
    for k in "${keys[@]}"; do
        if ! grep -qE "^${k}=" "$target"; then
            local v
            v="$(envgen_default_for "$k")"
            {
                printf '\n# Added by install.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
                printf '%s=%s\n' "$k" "$v"
            } >> "$target"
            appended=$((appended+1))
        fi
    done
    if (( appended > 0 )); then
        c_ok "Appended $appended new key(s) to $target"
    else
        c_dim "  No new keys to merge — .env up to date."
    fi
}

# Keys this version no longer reads. Each backend now follows the service's
# variant; a retired key left in .env would read as if it still chose one.
ENVGEN_RETIRED_KEYS=(
    BABA_DECODER_BACKENDS BABA_DETECTOR_BACKENDS BABA_DETECTOR_GPU_NV12
    BABA_INFERENCE_PROVIDERS BABA_API_INFERENCE_PROVIDERS
    BABA_REQUIRE_GPU BABA_REQUIRE_HW_DECODE
)

# The decoder an old BABA_DECODER_BACKENDS chain ran on (its head), when the
# ingestor would not pick it by itself: prints nothing when there is no chain,
# when the head was deleted with the RGB GPU decoders, or when it is the
# ingestor variant's own decoder (_DEFAULT_DECODER in the ingestor's
# config.py), so only a real per-host choice such as qsv-nv12 is pinned.
envgen_carried_decoder() {
    local chain head variant default
    chain="$(envgen_read "$1" BABA_DECODER_BACKENDS)" || return 0
    head="${chain%%,*}"; head="${head// /}"
    variant="$(envgen_read "$1" BABA_INGESTOR_VARIANT || envgen_read "$1" BABA_VARIANT || echo cpu)"
    case "$variant" in
        nvidia) default="ffmpeg-nvdec-nv12" ;;
        intel)  default="vaapi-nv12" ;;
        *)      default="software" ;;
    esac
    case "$head" in
        "$default") ;;
        *-nv12|software) printf '%s' "$head" ;;
    esac
}

# Remove the retired keys from an existing .env, each with the comment block
# directly above it (a "# ===" section rule and everything above it stays).
# The head of an old BABA_DECODER_BACKENDS chain carries over as
# BABA_DECODER_BACKEND when it is a per-host choice (envgen_carried_decoder),
# so a host pinned to qsv-nv12 keeps it. Backed up once, every change printed, written
# through the existing inode (.env may be bind-mounted). Run before
# envgen_merge_missing, which would otherwise seed BABA_DECODER_BACKEND empty.
envgen_retire() {
    local target="$1"
    if [[ ! -f "$target" ]]; then
        c_err "envgen_retire: $target does not exist"
        return 1
    fi
    local k found=()
    for k in "${ENVGEN_RETIRED_KEYS[@]}"; do
        grep -qE "^${k}=" "$target" && found+=("$k")
    done
    (( ${#found[@]} == 0 )) && return 0

    envgen_backup "$target"

    local chain carried=""
    if chain="$(envgen_read "$target" BABA_DECODER_BACKENDS)" \
            && [[ -z "$(envgen_read "$target" BABA_DECODER_BACKEND || echo "")" ]]; then
        carried="$(envgen_carried_decoder "$target")"
        case "${chain%%,*}" in
            *-nv12|software) ;;
            *) c_warn "  BABA_DECODER_BACKENDS=$chain: its first decoder no longer exists — the variant's decoder applies" ;;
        esac
    fi

    local tmp
    tmp=$(mktemp)
    ENVGEN_RETIRED="${ENVGEN_RETIRED_KEYS[*]}" ENVGEN_CARRIED="$carried" awk '
        BEGIN {
            n = split(ENVIRON["ENVGEN_RETIRED"], ks, " ")
            for (i = 1; i <= n; i++) retired[ks[i]] = 1
            carried = ENVIRON["ENVGEN_CARRIED"]
        }
        function flush(   i) { for (i = 1; i <= nb; i++) out(buf[i]); nb = 0 }
        function out(l) { print l; last_blank = (l == "") }
        /^[ \t]*#/ {
            if ($0 ~ /^#[ \t]*=+[ \t]*$/) { flush(); out($0); next }
            buf[++nb] = $0; next
        }
        /^[ \t]*$/ {
            flush()
            if (!(dropped && last_blank)) out($0)
            dropped = 0; next
        }
        {
            key = $0; sub(/=.*/, "", key)
            if (key in retired) {
                nb = 0; dropped = 1
                if (key == "BABA_DECODER_BACKENDS" && carried != "") out("BABA_DECODER_BACKEND=" carried)
                next
            }
            if (key == "BABA_DECODER_BACKEND" && carried != "") { nb = 0; dropped = 1; next }
            flush(); out($0); dropped = 0
        }
        END { flush() }' "$target" > "$tmp"
    cat "$tmp" > "$target"
    rm -f "$tmp"

    [[ -n "$carried" ]] && c_ok "  BABA_DECODER_BACKEND: <empty> → $carried (head of the retired chain)"
    for k in "${found[@]}"; do
        c_ok "  $k: removed (the variant decides)"
    done
    return 0
}

# Set each named key to the value of the shell variable of the same name,
# in place: keys not named, comments and order stay as they are. Every
# change is printed, and the file is backed up once before the first one.
# Written through the existing inode, because .env may be bind-mounted.
envgen_apply() {
    local target="$1"; shift
    local k old new backed_up=0 changed=0 tmp
    for k in "$@"; do
        new="${!k-}"
        old="$(envgen_read "$target" "$k" || echo "")"
        [[ "$old" == "$new" ]] && continue
        if (( backed_up == 0 )); then
            envgen_backup "$target"
            backed_up=1
        fi
        tmp=$(mktemp)
        ENVGEN_KEY="$k" ENVGEN_VAL="$new" awk '
            BEGIN { k = ENVIRON["ENVGEN_KEY"]; v = ENVIRON["ENVGEN_VAL"] }
            index($0, k "=") == 1 { last = NR }
            { line[NR] = $0 }
            END {
                for (i = 1; i <= NR; i++) print (i == last ? k "=" v : line[i])
                if (!last) print k "=" v
            }' "$target" > "$tmp"
        cat "$tmp" > "$target"
        rm -f "$tmp"
        case "$k" in
            *PASSWORD*|*SECRET*) c_ok "  $k: $([[ -n "$old" ]] && echo replaced || echo set)" ;;
            *) c_ok "  $k: ${old:-<empty>} → ${new:-<empty>}" ;;
        esac
        changed=$((changed+1))
    done
    (( changed == 0 )) && c_dim "  Configuration unchanged."
    return 0
}

