# Read a key from an existing .env into stdout. Returns empty + 1 if
# absent. Tolerant of `KEY=value`, `KEY="value"`, and trailing comments.
envgen_read() {
    local target="$1" key="$2"
    if [[ ! -f "$target" ]]; then return 1; fi
    local line
    line=$(grep -E "^${key}=" "$target" | tail -1) || return 1
    if [[ -z "$line" ]]; then return 1; fi
    # Strip "KEY=", optional surrounding quotes, optional trailing
    # whitespace. Don't strip in-value spaces — passwords may legit
    # contain them, even if we don't generate ones that do.
    local val="${line#${key}=}"
    val="${val%\"}"; val="${val#\"}"
    val="${val%\'}"; val="${val#\'}"
    printf '%s' "$val"
}
